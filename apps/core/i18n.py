def normalize_language(lang):
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def get_ui(lang):
    return UI_TEXT[normalize_language(lang)]


def localize_text(value, lang):
    if not value or lang == "ru":
        return value
    translations = LOCAL_TEXT.get(str(value))
    if not translations:
        return value
    return translations.get(normalize_language(lang), value)
